"""Freeze the compact HDMI OSD glyphs as a self-contained synchronous ROM.

Only this generator reads the installed font files.  The generated RTL contains
all bitmap values explicitly and has no file-path or runtime font dependency.
The first 90 Chinese IDs were agreed with the panel implementation; appended
mode characters keep those IDs unchanged.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CHINESE_INITIAL = (
    "帧延迟模式直方图横纵面积远程本地无目标红绿蓝三角圆正方矩形斑块锁定丢失运动计数"
    "电路板按键检测就绪扫描通过失败复核等待链错原灰度阈值反色彩量化浮雕边缘锐饱和暖冷"
    "怀旧素描伽马增益低高对比暗亮"
)
CHINESE_APPEND = "减阶虹腐蚀膨胀态提卡通误"
CHINESE = "".join(dict.fromkeys(CHINESE_INITIAL + CHINESE_APPEND))
GLYPH_COUNT = 128 + len(CHINESE)
DEFAULT_ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def raster_chinese(char: str, font: ImageFont.FreeTypeFont) -> tuple[Image.Image, dict]:
    # Rasterize into padding first.  Compare all set pixels with the cropped
    # cell to prove that the 16x16 conversion did not discard font ink.
    padded = Image.new("1", (48, 48))
    ImageDraw.Draw(padded).text((16, 16), char, font=font, fill=1)
    cell = padded.crop((16, 16, 32, 32))
    if not cell.getbbox():
        raise ValueError(f"empty Chinese glyph U+{ord(char):04X}")
    all_pixels = sum(bool(x) for x in padded.getdata())
    cell_pixels = sum(bool(x) for x in cell.getdata())
    if all_pixels != cell_pixels:
        raise ValueError(f"Chinese glyph U+{ord(char):04X} is clipped")
    return cell, {
        "ink_bbox": list(cell.getbbox()),
        "ink_pixels": cell_pixels,
        "padding_ink_pixels": all_pixels - cell_pixels,
        "nonempty": True,
        "clipped": False,
    }


def raster_ascii(char: str, font: ImageFont.FreeTypeFont) -> tuple[Image.Image, dict]:
    # Rasterize the complete Consolas 17px ink bounding box before fitting.
    # Capitals/digits have a 14px body, close to the native Chinese 15px.
    # Only ASCII is resampled: nearest-neighbour binary fitting, never crop
    # overhanging W/M/@/j. Punctuation retains its typographic relative height.
    source = Image.new("1", (8, 16))
    padded = Image.new("1", (40, 48))
    ImageDraw.Draw(padded).text((16, 16), char, font=font, fill=1)
    bbox = padded.getbbox()
    transformed = None
    if bbox:
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        crop = padded.crop(bbox)
        if sum(bool(x) for x in crop.getdata()) != sum(bool(x) for x in padded.getdata()):
            raise ValueError(f"ASCII glyph {char!r} bounding-box scan lost ink")
        target_w = min(w, 8)
        target_h = 14 if char.isupper() or char.isdigit() else min(14, max(1, (h * 14 + 5) // 11))
        y = max(1, min(15 - target_h, 1 + ((bbox[1] - 18) * 14 + 5) // 11))
        fitted = crop.resize((target_w, target_h), Image.Resampling.NEAREST)
        source.paste(fitted, ((8 - target_w) // 2, y))
        if not fitted.getbbox() or sum(bool(x) for x in source.getdata()) != sum(bool(x) for x in fitted.getdata()):
            raise ValueError(f"ASCII glyph {char!r} fitting clipped ink")
        transformed = {"raw_ink_bbox": list(bbox), "raw_ink_pixels": sum(bool(x) for x in crop.getdata()),
                       "fitted_pixels": [target_w, target_h], "fit_y": y,
                       "method": "complete tight bbox, binary nearest-neighbour fit; no crop"}
    cell = Image.new("1", (16, 16))
    cell.paste(source, (4, 0))
    return cell, {
        "ink_bbox": list(cell.getbbox()) if cell.getbbox() else None,
        "ink_pixels": sum(bool(x) for x in cell.getdata()),
        "source_cell": [8, 16],
        "source_x": 4,
        "raster_transform": transformed,
        "clipped": False,
    }


def rows_of(image: Image.Image) -> list[int]:
    return [sum((1 << (15 - x)) for x in range(16) if image.getpixel((x, y)))
            for y in range(16)]


def write_header(path: Path) -> None:
    lines = ["// Generated by tools/generate_compact_font.py; ID = local glyph index.",
             "// ASCII 0x20..0x7E stays ASCII. Chinese is U+named; not UTF-8.",
             "`ifndef OSD_COMPACT_GLYPHS_VH", "`define OSD_COMPACT_GLYPHS_VH",
             f"`define OSD_COMPACT_GLYPH_COUNT {GLYPH_COUNT}"]
    lines.extend(f"`define OSD_CN_U{ord(char):04X} 8'h{128 + i:02X} // {char}"
                 for i, char in enumerate(CHINESE))
    lines += ["`endif", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def write_rom(path: Path, glyphs: dict[int, tuple[str, Image.Image, dict]]) -> None:
    depth = GLYPH_COUNT * 16
    lines = [
        "// Generated self-contained 16x16 OSD bitmap ROM.",
        "// One synchronous read, no reset. row_bits[15] is the left pixel.",
        "// ASCII uses a centered 8x16 source cell; Chinese is native 16x16.",
        "// No readmemh/readmemb or runtime font dependency.",
        "module osd_compact_font_rom(",
        "    input wire clk,", "    input wire [7:0] glyph,",
        "    input wire [3:0] row,",
        "    output reg [15:0] row_bits", ");",
        f"    (* ram_style = \"bram\" *) reg [15:0] glyph_rom [0:{depth - 1}];",
        f"    wire [7:0] bounded_glyph = (glyph < 8'd{GLYPH_COUNT}) ? glyph : 8'h20;",
        "    wire [11:0] address = {bounded_glyph, row};",
        "    initial begin",
    ]
    for glyph in range(GLYPH_COUNT):
        char, bitmap, _ = glyphs[glyph]
        label = char if glyph >= 32 else "reserved"
        if glyph == 127:
            label = "reserved"
        lines.append(f"        // Glyph 0x{glyph:02X}: {label}")
        lines.extend(f"        glyph_rom[{glyph * 16 + row}] = 16'h{bits:04X};"
                     for row, bits in enumerate(rows_of(bitmap)))
    lines += ["    end",
              "    always @(posedge clk) row_bits <= glyph_rom[address];",
              "endmodule", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def draw_bitmap(draw: ImageDraw.ImageDraw, bitmap: Image.Image, x: int, y: int,
                scale: int, color: tuple[int, int, int]) -> None:
    for py in range(16):
        for px in range(16):
            if bitmap.getpixel((px, py)):
                draw.rectangle((x + px * scale, y + py * scale,
                                x + (px + 1) * scale - 1, y + (py + 1) * scale - 1),
                               fill=color)


def preview(path: Path, glyphs: dict[int, tuple[str, Image.Image, dict]],
            title_font: ImageFont.FreeTypeFont) -> None:
    columns, cw, ch = 16, 64, 70
    ordered = [x for x in range(32, 127)] + list(range(128, GLYPH_COUNT))
    image = Image.new("RGB", (columns * cw, 42 + ((len(ordered) + 15) // 16) * ch),
                      (8, 16, 24))
    draw = ImageDraw.Draw(image)
    draw.text((12, 10), "Compact OSD: 16x16 cells / native bitmap / 2x preview",
              font=title_font, fill=(224, 232, 240))
    for i, glyph in enumerate(ordered):
        x, y = (i % columns) * cw, 42 + (i // columns) * ch
        draw.rectangle((x + 7, y + 2, x + 42, y + 37), outline=(40, 66, 82))
        draw_bitmap(draw, glyphs[glyph][1], x + 9, y + 4, 2,
                    (98, 229, 234) if glyph >= 128 else (255, 224, 112))
        draw.text((x + 9, y + 42), f"{glyph:02X}", font=title_font, fill=(180, 190, 200))
    image.save(path)


def compare_preview(path: Path, fonts_dir: Path, label_font: ImageFont.FreeTypeFont) -> None:
    samples = "帧延迟模式运动计数电路板检测就绪通过失败复核等待链错横纵面积灰度阈值锐边腐蚀膨胀"
    variants = [("SimSun 16px (selected)", "simsun.ttc", 16),
                ("SimSun 15px", "simsun.ttc", 15),
                ("SimHei 16px", "simhei.ttf", 16)]
    columns = 32
    section_height = 136
    image = Image.new("RGB", (1048, 3 * section_height + 8), (8, 16, 24))
    draw = ImageDraw.Draw(image)
    for index, (name, filename, size) in enumerate(variants):
        y = 12 + index * section_height
        draw.text((12, y), name, font=label_font, fill=(224, 232, 240))
        font = ImageFont.truetype(str(fonts_dir / filename), size)
        for i, char in enumerate(samples):
            # Give the alternative faces the same cell and never scale
            # individual glyphs to fill their bounding box.
            bmp, _ = raster_chinese(char, font)
            draw_bitmap(draw, bmp, 12 + (i % columns) * 32,
                        y + 27 + (i // columns) * 36, 2, (98, 229, 234))
    image.save(path)


def mixed_preview(path: Path, glyphs: dict[int, tuple[str, Image.Image, dict]],
                  label_font: ImageFont.FreeTypeFont) -> None:
    image = Image.new("RGB", (1080, 322), (8, 16, 24))
    draw = ImageDraw.Draw(image)
    chinese_ids = {char: gid for gid, (char, _, _) in glyphs.items() if gid >= 128}
    samples = ["帧0123456789延迟123.4", "模式CNN PCB RGB", "横1280纵0720面积921600",
               "运动计数65535WM@gj"]
    draw.text((12, 8), "ASCII body 14px / Chinese native 15px; 16px cells", font=label_font, fill=(224,232,240))
    draw.text((12, 32), "native 1x", font=label_font, fill=(224,232,240))
    draw.text((478, 32), "nearest-neighbour 2x", font=label_font, fill=(224,232,240))
    for line, text in enumerate(samples):
        for scale, x0 in ((1, 12), (2, 478)):
            y = 65 + line * 57
            for index, char in enumerate(text):
                gid = chinese_ids[char] if char in chinese_ids else ord(char)
                color = (98,229,234) if gid >= 128 else (255,224,112)
                draw_bitmap(draw, glyphs[gid][1], x0 + index * 16 * scale, y, scale, color)
    image.save(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--fonts", type=Path, default=Path("C:/Windows/Fonts"))
    args = parser.parse_args()
    rtl = args.root / "01_rtl/imgq_gain_m/main/user_source/hdl_source"
    model = args.root / "model"
    preview_dir = args.root / "previews"
    for directory in (rtl, model, preview_dir):
        directory.mkdir(parents=True, exist_ok=True)
    if len("".join(dict.fromkeys(CHINESE_INITIAL))) != 90 or GLYPH_COUNT > 256:
        raise ValueError("fixed Chinese ID contract changed or overflow")
    cn_path = args.fonts / "simsun.ttc"
    ascii_path = args.fonts / "consola.ttf"
    cn_font = ImageFont.truetype(str(cn_path), 16)
    ascii_font = ImageFont.truetype(str(ascii_path), 17)
    title_font = ImageFont.truetype(str(ascii_path), 14)
    glyphs = {i: ("", Image.new("1", (16, 16)), {"reserved": True})
              for i in range(GLYPH_COUNT)}
    for i in range(32, 127):
        bitmap, detail = raster_ascii(chr(i), ascii_font)
        glyphs[i] = chr(i), bitmap, detail
    for i, char in enumerate(CHINESE, 128):
        bitmap, detail = raster_chinese(char, cn_font)
        glyphs[i] = char, bitmap, detail
    header_path = rtl / "osd_compact_glyphs.vh"
    rom_path = rtl / "osd_compact_font_rom.v"
    write_header(header_path)
    write_rom(rom_path, glyphs)
    # Independently parse the emitted assignments and compare every ROM word
    # with the Pillow result; this also rejects missing or duplicate entries.
    words = re.findall(r"glyph_rom\[(\d+)\] = 16'h([0-9A-F]{4});",
                       rom_path.read_text(encoding="utf-8"))
    emitted = {int(address): int(value, 16) for address, value in words}
    expected = {glyph * 16 + row: value
                for glyph, (_, bitmap, _) in glyphs.items()
                for row, value in enumerate(rows_of(bitmap))}
    if len(words) != len(expected) or emitted != expected:
        raise ValueError("ROM assignment integrity failure")
    preview_path = preview_dir / "compact_font_atlas.png"
    comparison_path = preview_dir / "compact_font_comparison.png"
    mixed_path = preview_dir / "compact_font_native_2x_mixed.png"
    preview(preview_path, glyphs, title_font)
    compare_preview(comparison_path, args.fonts, title_font)
    mixed_preview(mixed_path, glyphs, title_font)
    manifest = {
        "format": "local glyph ID, 16 rows, MSB is leftmost, one ROM clock",
        "cell_pixels": [16, 16], "ascii_source_pixels": [8, 16],
        "chinese_count": len(CHINESE), "glyph_count": GLYPH_COUNT,
        "rom_depth_words": GLYPH_COUNT * 16, "rom_word_bits": 16,
        "chinese_id_first": 128, "chinese_id_last": GLYPH_COUNT - 1,
        "runtime_font_dependency": False,
        "validation": {"status": "PASS", "rom_words_compared": len(expected),
                       "duplicate_addresses": 0, "missing_addresses": 0,
                       "nonempty_chinese_checked": len(CHINESE),
                       "clipped_chinese": 0,
                       "ascii_outside_centered_source": 0},
        "font_sources": [
            {"path": str(cn_path), "size": 16, "sha256": sha256(cn_path)},
            {"path": str(ascii_path), "size": 17, "sha256": sha256(ascii_path),
             "fitting": "complete glyph bbox to at most 8x14, nearest neighbour, capitals/digits body14"},
        ],
        "assets": {str(p.relative_to(args.root)): sha256(p)
                   for p in (header_path, rom_path, preview_path, comparison_path, mixed_path)},
        "generator_sha256": sha256(Path(__file__)),
        "glyphs": [{"id": i, "hex_id": f"{i:02X}", "character": char,
                    "unicode": f"U+{ord(char):04X}" if char else None,
                    "macro": f"OSD_CN_U{ord(char):04X}" if i >= 128 else None,
                    "rows": [f"{bits:04X}" for bits in rows_of(bitmap)], **detail}
                   for i, (char, bitmap, detail) in glyphs.items()],
    }
    manifest_path = model / "font_glyphs.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
                             encoding="utf-8")
    print(json.dumps({"status": "PASS", "chinese_count": len(CHINESE),
                      "glyph_count": GLYPH_COUNT, "depth": GLYPH_COUNT * 16,
                      "manifest_sha256": sha256(manifest_path),
                      "assets": manifest["assets"]}, ensure_ascii=True))


if __name__ == "__main__":
    main()
