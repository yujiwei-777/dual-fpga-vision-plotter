// Compact Chinese OSD only; all numerical inputs are already packed BCD.
// s1 emits the shared synchronous font ROM address.  At s2 the ROM output
// and the pixel column/valid/color refer to the same original x/y sample.
`include "osd_compact_glyphs.vh"
module osd_compact_panel #(parameter PAPER_STATUS_ENABLE=1'b1)(
    input wire clk, rst_n,
    input wire [11:0] x,y,
    input wire pcb_mode,
    input wire [2:0] pcb_status,
    input wire pcb_suspect,
    input wire [4:0] algo_mode,
    input wire he_on,lat_valid,lat_overflow,
    input wire [19:0] frame_bcd,
    input wire [15:0] lat_bcd,target_x_bcd,target_y_bcd,
    input wire [23:0] area_bcd,
    input wire remote,ovl_valid,
    input wire [1:0] target_color,shape3,
    input wire target_shape,motion_enable,
    input wire [19:0] motion_bcd,
    input wire multi_active,
    input wire recognition_enable,
    input wire [3:0] multi_slots,
    input wire [15:0] multi_classes,
    input wire [47:0] multi_conf_bcd,
    input wire operator_valid,
    input wire [152:0] operator_data,
    input wire [3:0] operator_digit,
    output wire [6:0] operator_digit_addr,
    output wire panel_on,panel_border,text_on,
    output wire [23:0] text_color,
    output wire [7:0] font_glyph,
    output wire [3:0] font_row,
    input wire [15:0] font_row_bits
);
    localparam [3:0] C_LABEL=4'd1,C_NUMBER=4'd2,C_MODE=4'd3,C_GOOD=4'd4,C_WAIT=4'd5,C_BAD=4'd6,C_RED=4'd7,C_GREEN=4'd8,C_BLUE=4'd9;
    reg panel_c,border_c,valid_c;
    reg [7:0] glyph_c;
    // Select literals or raw decimal nibbles before the single ASCII check.
    // Tag bit 8 is set only by an original decimal selection.
    reg [8:0] glyph_select_c;
    reg digit_enable_c;
    reg [3:0] digit_nibble_c;
    reg [3:0] row_c,col_c;
    reg [3:0] color_c;
    reg [11:0] local_x,local_y;
    reg [4:0] cell_idx;
    reg [2:0] line;
    reg pcb_text;
    reg operator_text;
    reg multi_text;
    reg multi_coord;
    wire recognition_on=(recognition_enable!==1'b0);
    reg [1:0] multi_slot;
    wire multi_mode=(multi_active===1'b1)&&recognition_on&&!pcb_mode;
    // The Type21 mailbox remains valid while the secondary is online, but
    // its panel is useful only when a cached result is waiting for KEY1 or a
    // printer task is active.  Bit 0 is the preview/waiting flag and bit 1
    // is the accepted-task/maintenance-busy flag in the compact metadata.
    // Page-full/recovery flags still request operator attention. Gate the
    // whole panel so ordinary completed/idle status cannot occupy the corner.
    wire operator_show=(operator_valid===1'b1)&&
                       ((operator_data[0]===1'b1)||(operator_data[1]===1'b1)||
                        (PAPER_STATUS_ENABLE&&(operator_data[2]===1'b1))||(operator_data[3]===1'b1));
    wire [3:0] multi_class=multi_classes[{multi_slot,2'b00}+:4];
    wire [11:0] multi_conf=({12{multi_slot==0}}&multi_conf_bcd[11:0])|
        ({12{multi_slot==1}}&multi_conf_bcd[23:12])|
        ({12{multi_slot==2}}&multi_conf_bcd[35:24])|
        ({12{multi_slot==3}}&multi_conf_bcd[47:36]);
    wire [3:0] multi_digit=(cell_idx==7)?multi_conf[11:8]:(cell_idx==8)?multi_conf[7:4]:multi_conf[3:0];
    reg operator_s1;
    reg static_s1;
    reg [5:0] static_key;
    reg dynamic_cell;
    wire [8:0] static_token;
    wire [5:0] operator_key;
    merged_panel_tokens u_shared_tokens(.clk(clk),.operator_mode(operator_text),
        .key(operator_text?operator_key:static_key),.col(cell_idx),.token(static_token));
    always @*begin
        static_key=0;dynamic_cell=0;
        if(!operator_text)begin
            if(multi_text)begin
                static_key=(multi_class>=1&&multi_class<=9)?6'd53+{2'd0,multi_class}:6'd0;
                dynamic_cell=multi_coord||(cell_idx>=7&&cell_idx<=10);
                if(multi_coord)static_key=0;
            end else if(pcb_text)case(line)
                0:static_key=36;
                1:static_key=37;
                2:static_key=6'd38+{3'd0,pcb_status}; // Status only; region graphics stay independent.
            endcase
            else case(line)
                0:begin static_key=1;dynamic_cell=(cell_idx>=2&&cell_idx<=6)||(cell_idx>=11&&cell_idx<=17);end
                1:begin static_key=6'd2+{1'd0,algo_mode};dynamic_cell=multi_mode&&motion_enable&&cell_idx>=7&&cell_idx<=16;end
                2:begin static_key=34;dynamic_cell=(cell_idx>=2&&cell_idx<=5)||(cell_idx>=8&&cell_idx<=11)||(cell_idx>=14&&cell_idx<=19);end
                3:dynamic_cell=1;
                4:begin static_key=35;dynamic_cell=(cell_idx>=5&&cell_idx<=9);end
            endcase
        end
    end
    wire [5:0] operator_addr;
    wire coord_y=(cell_idx>=7);
    wire [3:0] coord_cell=coord_y?(cell_idx-5'd9):(cell_idx-5'd2);
    wire [3:0] coord_word=4'd6+{1'b0,multi_slot,1'b0}+{3'd0,coord_y};
    assign operator_digit_addr=(multi_text&&multi_coord)?{coord_word,3'd3-coord_cell[2:0]}:{1'b0,operator_addr};
    wire [7:0] operator_glyph;
    operator_ui_text #(.PAPER_STATUS_ENABLE(PAPER_STATUS_ENABLE)) u_operator_text(.clk(clk),.valid(operator_show),.row(line),.col(cell_idx),
        .data(operator_data),.decimal_digit(operator_digit),.decimal_addr(operator_addr),.shared_token(static_token),.shared_key(operator_key),.glyph(operator_glyph));
    reg panel_s1,border_s1,valid_s1;
    reg [7:0] glyph_s1;
    reg [3:0] row_s1,col_s1;
    reg [3:0] color_s1;
    reg panel_s2,border_s2,valid_s2;
    reg [3:0] col_s2;
    reg [3:0] color_s2;

    // Palette index zero is the original reset black. Every published
    // index is a constant 1..10; decode after the unchanged two pixel stages.
    function [23:0] palette_decode;
        input [3:0] index;
        begin
            case(index)
                4'd1:palette_decode=24'h62e5ea;
                4'd2:palette_decode=24'hffe070;
                4'd3:palette_decode=24'hca9aff;
                4'd4:palette_decode=24'h70f080;
                4'd5:palette_decode=24'hffd060;
                4'd6:palette_decode=24'hff6060;
                4'd7:palette_decode=24'hff7070;
                4'd8:palette_decode=24'h70ef90;
                4'd9:palette_decode=24'h80b8ff;
                4'd10:palette_decode=24'hffff00;
                default:palette_decode=24'd0;
            endcase
        end
    endfunction

    function [7:0] digit;
        input [3:0] nibble;
        begin digit=(nibble<10)?(8'h30+{4'd0,nibble}):8'h3f; end
    endfunction

    // Surviving mode IDs retain their protocol meaning; IDs 5/15/16 retired.
    function [7:0] mode_char;
        input [4:0] mode;
        input second;
        begin
            case(mode)
                0:mode_char=second?`OSD_CN_U56FE:`OSD_CN_U539F; // original
                1:mode_char=second?`OSD_CN_U5EA6:`OSD_CN_U7070; // grayscale
                2:mode_char=second?`OSD_CN_U503C:`OSD_CN_U9608; // threshold
                3:mode_char=second?`OSD_CN_U8272:`OSD_CN_U53CD; // invert
                4:mode_char=second?`OSD_CN_U8272:`OSD_CN_U7EA2; // reduced color
                6:mode_char=second?`OSD_CN_U548C:`OSD_CN_U9971; // saturation
                7:mode_char=second?`OSD_CN_U7F18:`OSD_CN_U8FB9; // Sobel
                8:mode_char=second?`OSD_CN_U8FB9:`OSD_CN_U53CD; // edge processing
                9:mode_char=second?`OSD_CN_U96D5:`OSD_CN_U6D6E; // emboss
                10:mode_char=second?`OSD_CN_U8679:`OSD_CN_U5F69; // rainbow
                11:mode_char=second?`OSD_CN_U8680:`OSD_CN_U8150; // erode
                12:mode_char=second?`OSD_CN_U80C0:`OSD_CN_U81A8; // dilate
                13:mode_char=second?`OSD_CN_U6001:`OSD_CN_U5F62; // morphology
                14:mode_char=second?`OSD_CN_U8272:`OSD_CN_U84DD; // blue
                17:mode_char=second?`OSD_CN_U9A6C:`OSD_CN_U4F3D; // gamma
                18:mode_char=second?`OSD_CN_U901A:`OSD_CN_U5361; // cartoon
                default:mode_char=second?"?":"?";
            endcase
        end
    endfunction

    function [7:0] status_char;
        input [2:0] st;
        input [4:0] pos;
        begin
            status_char=" ";
            case(st)
                0:case(pos) 0:status_char=`OSD_CN_U5C31;1:status_char=`OSD_CN_U7EEA;endcase
                1:case(pos) 0:status_char=`OSD_CN_U626B;1:status_char=`OSD_CN_U63CF;endcase
                2:case(pos) 0:status_char=`OSD_CN_U901A;1:status_char=`OSD_CN_U8FC7;endcase
                3:case(pos) 0:status_char=`OSD_CN_U5931;1:status_char=`OSD_CN_U8D25;endcase
                4:case(pos) 0:status_char=`OSD_CN_U590D;1:status_char=`OSD_CN_U6838;endcase
                5:case(pos) 0:status_char=`OSD_CN_U65E0;1:status_char=`OSD_CN_U76EE;2:status_char=`OSD_CN_U6807;endcase
                6:case(pos) 0:status_char=`OSD_CN_U7B49;1:status_char=`OSD_CN_U5F85;2:status_char=`OSD_CN_U5C31;3:status_char=`OSD_CN_U7EEA;endcase
                7:case(pos) 0:status_char=`OSD_CN_U94FE;1:status_char=`OSD_CN_U8DEF;2:status_char=`OSD_CN_U9519;3:status_char=`OSD_CN_U8BEF;endcase
            endcase
        end
    endfunction

    always @(*) begin
        panel_c=0;border_c=0;valid_c=0;glyph_select_c=" ";row_c=0;col_c=0;
        color_c=C_LABEL;local_x=0;local_y=0;cell_idx=0;line=7;pcb_text=0;operator_text=0;multi_text=0;multi_coord=0;multi_slot=0;
        if(operator_show&&x>=800&&x<1264&&y>=224&&y<424)begin
            operator_text=1;panel_c=1;local_x=x-808;local_y=y-224;
            border_c=(x==800||x==1263||y==224||y==423);
            cell_idx=local_x[8:4];col_c=local_x[3:0];
            if(local_y>=8&&local_y<24)begin line=0;row_c=local_y-8;valid_c=1;end
            else if(local_y>=32&&local_y<48)begin line=1;row_c=local_y-32;valid_c=1;end
            else if(local_y>=56&&local_y<72)begin line=2;row_c=local_y-56;valid_c=1;end
            else if(local_y>=80&&local_y<96)begin line=3;row_c=local_y-80;valid_c=1;end
            else if(local_y>=104&&local_y<120)begin line=4;row_c=local_y-104;valid_c=1;end
            else if(local_y>=128&&local_y<144)begin line=5;row_c=local_y-128;valid_c=1;end
            else if(local_y>=152&&local_y<168)begin line=6;row_c=local_y-152;valid_c=1;end
            else if(local_y>=176&&local_y<192)begin line=7;row_c=local_y-176;valid_c=1;end
            valid_c=valid_c&&(x>=808)&&(x<1256);
        end else if(!pcb_mode && x>=864 && x<1200 && y>=64 && y<(multi_mode?304:recognition_on?(motion_enable?192:168):(motion_enable?192:120))) begin
            panel_c=1;local_x=x-872;local_y=y-64;
            border_c=(x==864 || x==1199 || y==64 || y==(multi_mode?303:recognition_on?(motion_enable?191:167):(motion_enable?191:119)));
            cell_idx=local_x[8:4];col_c=local_x[3:0];
            if(local_y>=8 && local_y<24) begin line=0;row_c=local_y-8;end
            else if(local_y>=32 && local_y<48) begin line=1;row_c=local_y-32;end
            else if(recognition_on&&local_y>=56 && local_y<72) begin line=2;row_c=local_y-56;end
            else if(multi_mode)begin
                if(local_y>=80&&local_y<96)begin multi_text=1;multi_slot=0;row_c=local_y-80;end
                else if(local_y>=100&&local_y<116)begin multi_text=1;multi_coord=1;multi_slot=0;row_c=local_y-100;end
                else if(local_y>=120&&local_y<136)begin multi_text=1;multi_slot=1;row_c=local_y-120;end
                else if(local_y>=140&&local_y<156)begin multi_text=1;multi_coord=1;multi_slot=1;row_c=local_y-140;end
                else if(local_y>=160&&local_y<176)begin multi_text=1;multi_slot=2;row_c=local_y-160;end
                else if(local_y>=180&&local_y<196)begin multi_text=1;multi_coord=1;multi_slot=2;row_c=local_y-180;end
                else if(local_y>=200&&local_y<216)begin multi_text=1;multi_slot=3;row_c=local_y-200;end
                else if(local_y>=220&&local_y<236)begin multi_text=1;multi_coord=1;multi_slot=3;row_c=local_y-220;end
            end else if(recognition_on&&local_y>=80 && local_y<96) begin line=3;row_c=local_y-80;end
            else if(motion_enable && local_y>=104 && local_y<120) begin line=4;row_c=local_y-104;end
            valid_c=((line!=7)||multi_text)&&(x>=872)&&(!multi_text||
                (multi_slots[multi_slot]&&multi_class>=1&&multi_class<=9));
        end else if(pcb_mode && x>=24 && x<312 && y>=584 && y<680) begin
            pcb_text=1;panel_c=1;local_x=x-32;local_y=y-584;
            border_c=(x==24 || x==311 || y==584 || y==679);
            cell_idx=local_x[8:4];col_c=local_x[3:0];
            if(local_y>=8 && local_y<24) begin line=0;row_c=local_y-8;end
            else if(local_y>=40 && local_y<56) begin line=1;row_c=local_y-40;end
            else if(local_y>=72 && local_y<88) begin line=2;row_c=local_y-72;end
            valid_c=(line!=7)&&(x>=32);
        end
        if(operator_text)begin
            glyph_select_c=operator_glyph;
            color_c=(operator_data[3]||(PAPER_STATUS_ENABLE&&operator_data[2])||operator_data[13:11]==5)?C_BAD:C_NUMBER;
        end else if(multi_text)begin
            color_c=(multi_class<=3)?C_RED:(multi_class<=6)?C_GREEN:C_BLUE;
            if(multi_coord)begin
                color_c=C_NUMBER;
                case(cell_idx)
                    0:glyph_select_c="X";
                    1,8:glyph_select_c=":";
                    2,3,4,5,9,10,11,12:glyph_select_c={1'b1,4'd0,operator_digit};
                    7:glyph_select_c="Y";
                    default:glyph_select_c=" ";
                endcase
            end else case(cell_idx)
                7,8,9:glyph_select_c={1'b1,4'd0,multi_digit};
                10:glyph_select_c="%";
            endcase
            if(cell_idx>=7)color_c=C_NUMBER;
        end else if(pcb_text)begin
            if(line==0)color_c=C_MODE;
            else if(line==2)begin
                case(pcb_status)
                    0,2:color_c=C_GOOD;
                    3,7:color_c=C_BAD;
                    default:color_c=C_WAIT;
                endcase
            end
        end else begin
            case(line)
                0:begin
                case(cell_idx)
                    2:glyph_select_c=lat_valid?{1'b1,4'd0,frame_bcd[19:16]}:"-";
                    3:glyph_select_c=lat_valid?{1'b1,4'd0,frame_bcd[15:12]}:"-";
                    4:glyph_select_c=lat_valid?{1'b1,4'd0,frame_bcd[11:8]}:"-";
                    5:glyph_select_c=lat_valid?{1'b1,4'd0,frame_bcd[7:4]}:"-";
                    6:glyph_select_c=lat_valid?{1'b1,4'd0,frame_bcd[3:0]}:"-";
                    11:glyph_select_c=!lat_valid?"N":lat_overflow?"O":{1'b1,4'd0,lat_bcd[15:12]};
                    12:glyph_select_c=!lat_valid?"/":lat_overflow?"V":{1'b1,4'd0,lat_bcd[11:8]};
                    13:glyph_select_c=!lat_valid?"A":lat_overflow?"F":{1'b1,4'd0,lat_bcd[7:4]};
                    14:glyph_select_c=(lat_valid&&!lat_overflow)?".":" ";
                    15:glyph_select_c=(lat_valid&&!lat_overflow)?{1'b1,4'd0,lat_bcd[3:0]}:" ";
                    16:glyph_select_c=(lat_valid&&!lat_overflow)?"M":" ";17:glyph_select_c=(lat_valid&&!lat_overflow)?"S":" ";
                endcase
                if((cell_idx>=2&&cell_idx<=6)||(cell_idx>=11))color_c=C_NUMBER;
                end
                1:begin
                    if(cell_idx>=3&&cell_idx<=4)color_c=C_MODE;
                    if(multi_mode&&motion_enable)begin
                        case(cell_idx)
                            7:glyph_select_c=`OSD_CN_U8FD0;8:glyph_select_c=`OSD_CN_U52A8;
                            9:glyph_select_c=`OSD_CN_U8BA1;10:glyph_select_c=`OSD_CN_U6570;11:glyph_select_c=":";
                            12:glyph_select_c={1'b1,4'd0,motion_bcd[19:16]};13:glyph_select_c={1'b1,4'd0,motion_bcd[15:12]};
                            14:glyph_select_c={1'b1,4'd0,motion_bcd[11:8]};15:glyph_select_c={1'b1,4'd0,motion_bcd[7:4]};
                            16:glyph_select_c={1'b1,4'd0,motion_bcd[3:0]};
                        endcase
                        if(cell_idx>=12)color_c=C_NUMBER;
                    end
                end
                2:begin
                    case(cell_idx)
                        2:glyph_select_c={1'b1,4'd0,target_x_bcd[15:12]};3:glyph_select_c={1'b1,4'd0,target_x_bcd[11:8]};
                        4:glyph_select_c={1'b1,4'd0,target_x_bcd[7:4]};5:glyph_select_c={1'b1,4'd0,target_x_bcd[3:0]};
                        8:glyph_select_c={1'b1,4'd0,target_y_bcd[15:12]};9:glyph_select_c={1'b1,4'd0,target_y_bcd[11:8]};
                        10:glyph_select_c={1'b1,4'd0,target_y_bcd[7:4]};11:glyph_select_c={1'b1,4'd0,target_y_bcd[3:0]};
                        14:glyph_select_c={1'b1,4'd0,area_bcd[23:20]};15:glyph_select_c={1'b1,4'd0,area_bcd[19:16]};
                        16:glyph_select_c={1'b1,4'd0,area_bcd[15:12]};17:glyph_select_c={1'b1,4'd0,area_bcd[11:8]};
                        18:glyph_select_c={1'b1,4'd0,area_bcd[7:4]};19:glyph_select_c={1'b1,4'd0,area_bcd[3:0]};
                    endcase
                    if((cell_idx>=2&&cell_idx<=5)||(cell_idx>=8&&cell_idx<=11)||(cell_idx>=14&&cell_idx<=19))color_c=C_NUMBER;
                end
                3:begin
                    case(cell_idx)
                        0:glyph_select_c=remote?`OSD_CN_U8FDC:`OSD_CN_U672C;1:glyph_select_c=remote?`OSD_CN_U7A0B:`OSD_CN_U5730;2:glyph_select_c=":";
                        3:glyph_select_c=!ovl_valid?`OSD_CN_U65E0:(target_color==0?`OSD_CN_U7EA2:target_color==1?`OSD_CN_U7EFF:`OSD_CN_U84DD);
                        5:glyph_select_c=!ovl_valid?`OSD_CN_U76EE:(remote?(shape3==1?`OSD_CN_U4E09:shape3==2?`OSD_CN_U5706:`OSD_CN_U6B63):(target_shape?`OSD_CN_U6591:`OSD_CN_U77E9));
                        6:glyph_select_c=!ovl_valid?`OSD_CN_U6807:(remote?(shape3==1?`OSD_CN_U89D2:shape3==2?`OSD_CN_U5F62:`OSD_CN_U65B9):(target_shape?`OSD_CN_U5757:`OSD_CN_U5F62));
                        7:glyph_select_c=(ovl_valid&&remote&&shape3!=1&&shape3!=2)?`OSD_CN_U5F62:" ";
                        10:glyph_select_c=ovl_valid?`OSD_CN_U9501:`OSD_CN_U4E22;11:glyph_select_c=ovl_valid?`OSD_CN_U5B9A:`OSD_CN_U5931;
                    endcase
                    if(cell_idx==3&&ovl_valid) color_c=(target_color==0)?C_RED:(target_color==1)?C_GREEN:C_BLUE;
                    else if(cell_idx>=5) color_c=ovl_valid?C_GOOD:C_WAIT;
                end
                4:begin
                    case(cell_idx)
                        5:glyph_select_c={1'b1,4'd0,motion_bcd[19:16]};6:glyph_select_c={1'b1,4'd0,motion_bcd[15:12]};7:glyph_select_c={1'b1,4'd0,motion_bcd[11:8]};
                        8:glyph_select_c={1'b1,4'd0,motion_bcd[7:4]};9:glyph_select_c={1'b1,4'd0,motion_bcd[3:0]};
                    endcase
                    if(cell_idx>=5)color_c=C_NUMBER;
                end
            endcase
        end
        digit_enable_c=glyph_select_c[8];
        digit_nibble_c=glyph_select_c[3:0];
        glyph_c=digit_enable_c?digit(digit_nibble_c):glyph_select_c[7:0];
    end

    always @(posedge clk or negedge rst_n) begin
        if(!rst_n) begin
            panel_s1<=0;border_s1<=0;valid_s1<=0;glyph_s1<=" ";row_s1<=0;col_s1<=0;color_s1<=0;operator_s1<=0;static_s1<=0;
            panel_s2<=0;border_s2<=0;valid_s2<=0;col_s2<=0;color_s2<=0;
        end else begin
            panel_s1<=panel_c;border_s1<=border_c;valid_s1<=valid_c;glyph_s1<=glyph_c;
            operator_s1<=operator_text;static_s1<=!dynamic_cell;
            row_s1<=row_c;col_s1<=col_c;color_s1<=color_c;
            panel_s2<=panel_s1;border_s2<=border_s1;valid_s2<=valid_s1;col_s2<=col_s1;color_s2<=color_s1;
        end
    end
    assign font_glyph=operator_s1?operator_glyph:static_s1?static_token[7:0]:glyph_s1;
    assign font_row=row_s1;
    assign panel_on=panel_s2;
    assign panel_border=border_s2;
    assign text_on=valid_s2&&font_row_bits[15-col_s2];
    assign text_color=palette_decode(color_s2);
endmodule

